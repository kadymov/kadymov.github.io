export function availableConversations(person, state) {
  return CONVERSATIONS.filter(topic => topic.person === person && state.life.inspected.includes(topic.object));
}

export function conversationNode(person, key, state, returnNode) {
  const topics = availableConversations(person, state);
  if (!topics.length) return null;
  const back = { label: 'Вернуться к разговору.', next: returnNode };
  if (key === 'observations') return {
    text: 'О чём из замеченного в штабе поговорим?',
    options: [...topics.map(topic => ({ label: topic.label, next: `observations:${topic.object}` })), back],
  };
  const topic = topics.find(topic => key === `observations:${topic.object}` || key === `observations:${topic.object}:reply`);
  if (!topic) return null;
  const followup = key.endsWith(':reply');
  return {
    text: followup ? topic.reply : topic.text,
    options: [
      ...(!followup ? [{ label: topic.question, next: `observations:${topic.object}:reply` }] : []),
      { label: 'О других находках в штабе.', next: 'observations' }, back,
    ],
  };
}
